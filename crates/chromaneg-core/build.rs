//! Turns `presets.toml` (tone profiles, film stocks and creative looks) into the constants of `presets.rs`.
//! A mistake in the file (an unknown field, a wrong type, a repeated name) stops the build with a
//! message saying where.

use std::fmt::Write as _;

/// A table: the TOML key, the Rust type and constant, and its fields with their neutral values.
type Table = (&'static str, &'static str, &'static str, &'static [(&'static str, Default)]);

const TABLES: [Table; 2] = [
    (
        "profile",
        "Profile",
        "PROFILES",
        &[
            ("slopes", Default::Arr(&[1.0; 3])),
            ("power", Default::Num(1.0)),
            ("lift", Default::Num(0.0)),
            ("gamma", Default::Num(1.0)),
            ("sat", Default::Num(1.0)),
        ],
    ),
    (
        "stock",
        "Stock",
        "STOCKS",
        &[
            ("crosstalk", Default::Num(1.0)),
            ("sat", Default::Num(1.0)),
            ("contrast", Default::Num(0.0)),
            ("darks", Default::Num(0.0)),
            ("temp", Default::Num(0.0)),
            ("tint", Default::Num(0.0)),
            ("shadows", Default::Arr(&[0.0; 3])),
            ("highlights", Default::Arr(&[0.0; 3])),
            ("hue_sat", Default::Arr(&[1.0; 6])),
            ("fade", Default::Num(0.0)),
        ],
    ),
];

#[derive(Clone, Copy)]
enum Default {
    Num(f64),
    Arr(&'static [f64]),
}

fn num(v: &toml::Value) -> Option<f64> {
    v.as_float().or_else(|| v.as_integer().map(|i| i as f64)).filter(|f| f.is_finite())
}

fn lit(f: f64) -> String {
    format!("{f:?}_f32")
}

fn main() -> Result<(), String> {
    println!("cargo::rerun-if-changed=presets.toml");
    let text = std::fs::read_to_string("presets.toml").map_err(|e| format!("presets.toml: {e}"))?;
    let doc: toml::Table = text.parse().map_err(|e| format!("presets.toml: {e}"))?;
    if let Some(k) = doc.keys().find(|k| !TABLES.iter().any(|t| t.0 == k.as_str())) {
        return Err(format!("presets.toml: unknown table [[{k}]] (expected profile or stock)"));
    }
    let mut out = String::from("// Generated by build.rs from presets.toml: edit that file instead.\n\n");
    for (key, ty, konst, fields) in TABLES {
        let entries = doc.get(key).and_then(toml::Value::as_array).ok_or_else(|| format!("presets.toml: no [[{key}]] entries"))?;
        let mut names = Vec::new();
        writeln!(out, "pub const {konst}: [{ty}; {}] = [", entries.len()).map_err(|e| e.to_string())?;
        for (i, e) in entries.iter().enumerate() {
            let at = format!("presets.toml: [[{key}]] #{}", i + 1);
            let e = e.as_table().ok_or_else(|| format!("{at}: not a table"))?;
            let name = e.get("name").and_then(toml::Value::as_str).ok_or_else(|| format!("{at}: needs a name"))?;
            if names.contains(&name) {
                return Err(format!("{at}: the name {name:?} is used twice"));
            }
            names.push(name);
            if let Some(k) = e.keys().find(|k| k.as_str() != "name" && !fields.iter().any(|f| f.0 == k.as_str())) {
                let known: Vec<&str> = fields.iter().map(|f| f.0).collect();
                return Err(format!("{at} ({name}): unknown field {k:?}; known: name, {}", known.join(", ")));
            }
            let mut s = format!("    {ty} {{ name: {name:?}");
            for (f, d) in fields {
                let v = match (e.get(*f), d) {
                    (None, Default::Num(x)) => lit(*x),
                    (None, Default::Arr(a)) => format!("[{}]", a.iter().map(|x| lit(*x)).collect::<Vec<_>>().join(", ")),
                    (Some(v), Default::Num(_)) => lit(num(v).ok_or_else(|| format!("{at} ({name}): {f} must be a number"))?),
                    (Some(v), Default::Arr(a)) => {
                        let xs: Option<Vec<f64>> = v.as_array().and_then(|xs| xs.iter().map(num).collect());
                        let xs = xs.filter(|xs| xs.len() == a.len()).ok_or_else(|| format!("{at} ({name}): {f} must be {} numbers", a.len()))?;
                        format!("[{}]", xs.iter().map(|x| lit(*x)).collect::<Vec<_>>().join(", "))
                    }
                };
                write!(s, ", {f}: {v}").map_err(|e| e.to_string())?;
            }
            writeln!(out, "{s} }},").map_err(|e| e.to_string())?;
        }
        writeln!(out, "];\n").map_err(|e| e.to_string())?;
    }
    let dir = std::env::var("OUT_DIR").map_err(|e| e.to_string())?;
    std::fs::write(std::path::Path::new(&dir).join("presets.rs"), out).map_err(|e| e.to_string())
}
